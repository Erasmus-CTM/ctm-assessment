// DIAGNOSTIC ONLY: compile tools/wkz/wat/*.wat into tools/wkz/wasm.js (base64
// table shared by the page, the worker and the standalone repro).
// Usage: node tools/wkz/build-wasm.mjs  (needs `npm i wabt@1.0.37`)
import fs from 'node:fs';
import path from 'node:path';
import wabtInit from 'wabt';
const dir = path.dirname(new URL(import.meta.url).pathname);
const wabt = await wabtInit();
const out = {};
for (const file of fs.readdirSync(path.join(dir, 'wat')).filter(f => f.endsWith('.wat')).sort()) {
  const features = {exceptions: true, threads: true};
  const mod = wabt.parseWat(file, fs.readFileSync(path.join(dir, "wat", file), "utf8"), features);
  mod.validate(features);
  out[file.replace(/\.wat$/, '')] = Buffer.from(mod.toBinary({}).buffer).toString('base64');
}
fs.writeFileSync(path.join(dir, 'wasm.js'), '// Generated by build-wasm.mjs from wat/*.wat. DIAGNOSTIC ONLY.\nself.WKZ_WASM=' + JSON.stringify(out, null, 1) + ';\n');
console.log(Object.keys(out).map(k => `${k}:${out[k].length}`).join(' '));
